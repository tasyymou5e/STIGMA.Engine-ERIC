import type { ResultSetHeader, RowDataPacket } from 'mysql2'
import { pool } from '../db/pool.js'

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

export interface Label {
  clId: number
  collectionId: number
  name: string
  description: string | null
  color: string | null
  assetCount?: number
}

export interface Asset {
  assetId: number
  collectionId: number
  name: string
  fqdn: string | null
  ip: string | null
}

// ---------------------------------------------------------------------------
// listLabels
// ---------------------------------------------------------------------------

/**
 * Return every label in a collection, including a count of assets currently
 * mapped to each label.
 */
export async function listLabels(collectionId: number): Promise<Label[]> {
  const [rows] = await pool.query<RowDataPacket[]>(
    `SELECT
       cl.clId,
       cl.collectionId,
       cl.name,
       cl.description,
       cl.color,
       COUNT(cla.assetId) AS assetCount
     FROM collection_label           cl
     LEFT JOIN collection_label_asset_map cla ON cl.clId = cla.clId
     WHERE cl.collectionId = :collectionId
     GROUP BY cl.clId
     ORDER BY cl.name`,
    { collectionId }
  )
  return rows as unknown as Label[]
}

// ---------------------------------------------------------------------------
// createLabel
// ---------------------------------------------------------------------------

/**
 * Insert a new label row.
 * A random UUID is generated by the database via UUID_TO_BIN(UUID(), 1) so
 * callers do not need to supply one.
 * Returns the new clId.
 */
export async function createLabel(
  collectionId: number,
  input: { name: string; description?: string; color?: string }
): Promise<number> {
  const [res] = await pool.query<ResultSetHeader>(
    `INSERT INTO collection_label (collectionId, name, description, color, uuid)
     VALUES (:collectionId, :name, :description, :color, UUID_TO_BIN(UUID(), 1))`,
    {
      collectionId,
      name: input.name,
      description: input.description ?? null,
      color: input.color ?? null
    }
  )
  return res.insertId
}

// ---------------------------------------------------------------------------
// updateLabel
// ---------------------------------------------------------------------------

/**
 * Partial UPDATE — only the fields present in `patch` are written.
 * Returns true when the row was found and at least one column value changed.
 */
export async function updateLabel(
  clId: number,
  patch: Partial<Pick<Label, 'name' | 'description' | 'color'>>
): Promise<boolean> {
  const setClauses: string[] = []
  const binds: Record<string, unknown> = { clId }

  if (patch.name !== undefined) {
    setClauses.push('name = :pName')
    binds.pName = patch.name
  }
  if (patch.description !== undefined) {
    setClauses.push('description = :pDescription')
    binds.pDescription = patch.description
  }
  if (patch.color !== undefined) {
    setClauses.push('color = :pColor')
    binds.pColor = patch.color
  }

  if (setClauses.length === 0) return false

  const [res] = await pool.query<ResultSetHeader>(
    `UPDATE collection_label SET ${setClauses.join(', ')} WHERE clId = :clId`,
    binds as unknown as import('mysql2').QueryValues
  )
  return res.affectedRows > 0
}

// ---------------------------------------------------------------------------
// deleteLabel
// ---------------------------------------------------------------------------

/**
 * Delete a label by its primary key.
 * Child rows in collection_label_asset_map and collection_grant_acl are
 * removed automatically via ON DELETE CASCADE.
 * Returns true when a row was actually deleted.
 */
export async function deleteLabel(clId: number): Promise<boolean> {
  const [res] = await pool.query<ResultSetHeader>(
    'DELETE FROM collection_label WHERE clId = :clId',
    { clId }
  )
  return res.affectedRows > 0
}

// ---------------------------------------------------------------------------
// listLabelAssets
// ---------------------------------------------------------------------------

/**
 * Return the assets currently mapped to a label, ordered by asset name.
 */
export async function listLabelAssets(clId: number): Promise<Asset[]> {
  const [rows] = await pool.query<RowDataPacket[]>(
    `SELECT
       a.assetId,
       a.collectionId,
       a.name,
       a.fqdn,
       a.ip
     FROM collection_label_asset_map cla
     INNER JOIN asset a ON cla.assetId = a.assetId
     WHERE cla.clId = :clId
     ORDER BY a.name`,
    { clId }
  )
  return rows as unknown as Asset[]
}

// ---------------------------------------------------------------------------
// setLabelAssets
// ---------------------------------------------------------------------------

/**
 * Replace the full asset membership of a label atomically.
 *
 * The existing mapping rows are deleted and the new set is inserted in a
 * single transaction so callers never observe a partially-updated state.
 * Passing an empty array clears all asset mappings for the label.
 */
export async function setLabelAssets(clId: number, assetIds: number[]): Promise<void> {
  const conn = await pool.getConnection()
  try {
    await conn.beginTransaction()

    await conn.query(
      'DELETE FROM collection_label_asset_map WHERE clId = ?',
      [clId]
    )

    if (assetIds.length > 0) {
      const values = assetIds.map(assetId => [assetId, clId])
      await conn.query(
        'INSERT INTO collection_label_asset_map (assetId, clId) VALUES ?',
        [values]
      )
    }

    await conn.commit()
  } catch (e) {
    await conn.rollback()
    throw e
  } finally {
    conn.release()
  }
}
